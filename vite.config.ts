import { writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { defineConfig, type Plugin } from "vite";
import react from "@vitejs/plugin-react";

/** Workers Static Assets allows at most 100 `_headers` rules. */
const MAX_HEADER_RULES = 100;

/**
 * Writes dist/client/_headers (Workers Static Assets custom headers).
 *
 * - The HTML shell is `no-cache`, so a redeploy is picked up on the next load.
 * - Every hashed file of THIS build is `immutable` for a year, listed by exact path.
 *
 * Why not `/assets/*`: with not_found_handling = "single-page-application", a request for a chunk
 * that no longer exists (an open tab after a redeploy) is answered with index.html (200, text/html).
 * A wildcard rule would stamp that HTML `immutable`, so the browser would keep the broken response
 * for a year even after a rollback brings the file back. Exact paths only match real files; anything
 * else keeps the platform default (`max-age=0, must-revalidate`).
 */
function assetHeaders(): Plugin {
  let outDir = "";
  return {
    name: "vexo-asset-headers",
    apply: "build",
    configResolved(c) {
      outDir = resolve(c.root, c.build.outDir);
    },
    writeBundle(opts, bundle) {
      const hashed = Object.keys(bundle)
        .filter((f) => f.startsWith("assets/"))
        .sort();
      const lines = [
        "# Generated by vite.config.ts (assetHeaders). Do not edit.",
        "/",
        "  Cache-Control: no-cache",
        "/index.html",
        "  Cache-Control: no-cache",
      ];
      if (hashed.length + 2 <= MAX_HEADER_RULES) {
        for (const f of hashed) lines.push(`/${f}`, "  Cache-Control: public, max-age=31536000, immutable");
      } else {
        this.warn(
          `${hashed.length} hashed assets exceed the ${MAX_HEADER_RULES}-rule _headers limit; ` +
            "they keep the default revalidating cache policy.",
        );
      }
      writeFileSync(join(opts.dir ?? outDir, "_headers"), lines.join("\n") + "\n");
    },
  };
}

// UI-only build. The Worker serves dist/client as static assets.
export default defineConfig({
  root: "src/ui",
  plugins: [react(), assetHeaders()],
  build: { outDir: "../../dist/client", emptyOutDir: true },
  server: { proxy: { "^/api/": "http://localhost:8787", "^/auth/": "http://localhost:8787" } },
});
